#!/usr/bin/env python3
"""Bundle image files into a JS file as data URIs, so a page opened from file://
(double-click on the .html, no server) can still use them as WebGL textures.

Why: Chrome gives every file:// document a unique origin, so an <img> loaded from
a sibling file "taints" any canvas it is drawn on, and three.js cannot upload a
tainted canvas as a texture — the cover and the photos come out black locally
while the very same page works on GitHub Pages. Data URIs are same-origin.

Usage:
  python3 bundle-assets.py <out.js> <globalName> <file> [<file>...]
  e.g.  python3 bundle-assets.py 3d-book/book-fx/spread/assets.js BOOK_ASSETS \\
          3d-book/book-fx/spread/cover.jpg 3d-book/book-fx/spread/containers.jpg 3d-book/book-fx/spread/solar.jpg

The page loads the bundle before its own script and reads window.<globalName>[basename].
Re-run after replacing any of the images.
"""
import base64, mimetypes, os, sys

if len(sys.argv) < 4:
    sys.exit(__doc__)
out, name, files = sys.argv[1], sys.argv[2], sys.argv[3:]
parts = []
for f in files:
    mime = mimetypes.guess_type(f)[0] or 'application/octet-stream'
    data = base64.b64encode(open(f, 'rb').read()).decode('ascii')
    parts.append('  %r: "data:%s;base64,%s"' % (os.path.basename(f), mime, data))
with open(out, 'w') as fh:
    fh.write('/* generated by experiments/bundle-assets.py — do not edit; re-run the script after replacing an image.\n'
             '   Images as data URIs so the page also works from file:// (see the script header). */\n')
    fh.write('window.%s = {\n%s\n};\n' % (name, ',\n'.join(parts)))
print('%s: %d files, %d KB' % (out, len(files), os.path.getsize(out) // 1024))
